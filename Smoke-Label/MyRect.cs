namespace Smoke_Label
{
    internal class MyRect
    {
        public float x;
        public float y;
        public float w;
        public float h;

        public MyRect()
        {
        }

        public MyRect(float x, float y, float w, float h)
        {
            this.x = x;
            this.y = y;
            this.w = w;
            this.h = h;
        }
    }
}
